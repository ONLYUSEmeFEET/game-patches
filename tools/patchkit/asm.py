"""Assembler runner, symbol-map parser, and debugger .sym exporter."""

from __future__ import annotations

import shutil
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path


class SymbolTable(dict[str, int]):
    """Case-insensitive symbol dictionary preserving stored names for display/.sym export."""

    def __init__(self, initial: dict[str, int] | None = None) -> None:
        super().__init__()
        self._by_upper: dict[str, str] = {}
        if initial:
            for k, v in initial.items():
                self[k] = v

    def __setitem__(self, key: str, value: int) -> None:
        upper = key.upper()
        if upper in self._by_upper and self._by_upper[upper] != key:
            super().__delitem__(self._by_upper[upper])
        self._by_upper[upper] = key
        super().__setitem__(key, value)

    def __getitem__(self, key: str) -> int:
        canonical = self._by_upper.get(key.upper())
        if canonical is None:
            raise KeyError(key)
        return super().__getitem__(canonical)

    def __contains__(self, key: object) -> bool:
        return isinstance(key, str) and key.upper() in self._by_upper

    def get(self, key: str, default: int | None = None) -> int | None:
        canonical = self._by_upper.get(key.upper())
        if canonical is None:
            return default
        return super().__getitem__(canonical)


@dataclass(frozen=True)
class AsmBuildResult:
    payload: bytes
    symbols: SymbolTable
    constants: SymbolTable


def parse_asw_map(map_path: str | Path) -> tuple[SymbolTable, SymbolTable]:
    """Parse an ASW `-g MAP` file into (code_symbols, user_constants)."""
    text = Path(map_path).read_text(encoding="utf-8", errors="replace")
    code_symbols = SymbolTable()
    constants = SymbolTable()

    section: str | None = None
    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        if line.startswith("Symbols in Segment "):
            section = line.removeprefix("Symbols in Segment ").strip()
            continue
        if line.startswith("Segment ") or line.startswith("File "):
            section = None
            continue
        if section not in ("CODE", "NOTHING"):
            continue

        parts = line.split()
        # Format: <NAME> <TYPE> <VALUE> <SCOPE> <USED>
        if len(parts) < 5 or parts[1] != "Int":
            continue
        name = parts[0]
        try:
            value = int(parts[2], 16)
            used = int(parts[4], 10)
        except ValueError:
            continue

        if section == "CODE":
            code_symbols[name] = value
        elif section == "NOTHING" and used > 0:
            constants[name] = value

    return code_symbols, constants


def assemble_asw(
    asm_path: str | Path,
    *,
    asw_bin: str | Path,
    p2bin_bin: str | Path,
    include_dirs: list[str | Path] | None = None,
) -> AsmBuildResult:
    """Assemble an ASW source file in an isolated temp dir and return binary + symbols."""
    entry = Path(asm_path).resolve()
    if not entry.is_file():
        raise FileNotFoundError(f"Assembly source not found: {entry}")

    inc_paths = [entry.parent]
    if include_dirs:
        inc_paths.extend(Path(p).resolve() for p in include_dirs)

    with tempfile.TemporaryDirectory() as tmpdir:
        tmp = Path(tmpdir)
        tmp_asm = tmp / entry.name
        shutil.copy2(entry, tmp_asm)

        p_path = tmp / f"{entry.stem}.p"
        bin_path = tmp / f"{entry.stem}.bin"
        map_path = tmp / f"{entry.stem}.map"

        cmd = [str(asw_bin), "-q", "-g", "MAP"]
        for inc in inc_paths:
            cmd.extend(["-i", str(inc)])
        cmd.extend(["-o", str(p_path), str(tmp_asm)])
        subprocess.run(cmd, check=True)

        subprocess.run(
            [str(p2bin_bin), "-r", "$-$", str(p_path), str(bin_path)],
            check=True,
        )

        payload = bin_path.read_bytes()
        code_symbols, constants = parse_asw_map(map_path)

    return AsmBuildResult(payload=payload, symbols=code_symbols, constants=constants)


def write_sym_file(
    symbols: dict[str, int],
    out_path: str | Path,
    *,
    constants: dict[str, int] | None = None,
) -> Path:
    """Export a clean address-sorted debugger .sym file."""
    path = Path(out_path)
    path.parent.mkdir(parents=True, exist_ok=True)

    lines = ["; Auto-generated by patchkit.asm"]
    lines.append("; [CODE LABELS]")
    for name, addr in sorted(symbols.items(), key=lambda kv: (kv[1], kv[0])):
        lines.append(f"{addr:08X} {name}")

    if constants:
        lines.append("")
        lines.append("; [CONSTANTS / RAM SYMBOLS]")
        for name, val in sorted(constants.items(), key=lambda kv: (kv[1], kv[0])):
            lines.append(f"{val:08X} {name}")

    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
